"""Build and slice-check the A2L board and the two single-colour A1 mini counter plates."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import importlib.util
import json
from pathlib import Path
import zipfile

import build123d as bd

ROOT = Path(__file__).resolve().parents[1]


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


design = load_module("do_guti", ROOT / "do-guti.py")
bambu = load_module("lettering_build", ROOT.parent / "streaming-lettering" / "tools" / "build.py")


class Project(bambu.Project):
    @property
    def key(self):
        return f"do-guti-{self.product}-{self.printer}"


def export_mesh(shape, path):
    if not shape.is_valid or not bd.export_stl(shape, str(path), tolerance=0.012, angular_tolerance=0.12):
        raise ValueError(f"Invalid geometry or export failure for {path.name}")
    if bambu.stl_bad_edges(path) or bambu.stl_slivers(path):
        raise ValueError(f"Open mesh or stray slivers in {path.name}")


def make_project(product, build, mark, jobs):
    meshes = build / "stl"
    meshes.mkdir(parents=True, exist_ok=True)
    if product == "board":
        bodies = design.board(mark)
        # The joined STL is also the one-body geometry for the printing DFM check.
        joined = bodies[0].fuse(*bodies[1:])
        if len(joined.solids()) != 1:
            raise ValueError("Board inlays must join the plate")
        export_mesh(joined, meshes / "board.stl")
        palette = [design.INDIGO, design.MADDER, design.WHITE, design.GREEN]
    else:
        bodies = [design.counter(True), design.counter(False)]
        palette = [design.MADDER, design.WHITE]

    def part(shape):
        name = shape.label
        path = meshes / (name.lower().replace(" ", "-") + ".stl")
        export_mesh(shape, path)
        rgb = tuple(shape.color)[:3]
        color = "#" + "".join(f"{round(channel * 255):02X}" for channel in rgb)
        slot = palette.index(color) + 1
        return bambu.Part(name, {}, slot, stl=path, bbox=bambu.stl_bbox(path))

    with ThreadPoolExecutor(max_workers=jobs) as pool:
        parts = list(pool.map(part, bodies))
    if product == "board":
        group = bambu.Group("Ajrak board", parts)
        return Project(product, "a2l", palette, [bambu.PlateSpec("Board", [group])])
    plates = []
    for name, piece in zip(["Madder pair", "White pair"], parts):
        pair = [bambu.Group(piece.name, [piece]) for _ in range(2)]
        plates.append(bambu.PlateSpec(name, pair))
    return Project(product, "a1-mini", palette, plates)


def write_summary(results, docs):
    docs.mkdir(parents=True, exist_ok=True)
    lines = ["# Build summary", "", "Generated by `tools/build.py` using Bambu Studio’s stock PLA Basic profiles.", "",
             "| Project | Plate | Time | Filament |", "|---|---|---:|---:|"]
    for result in results:
        for plate in result["plates"]:
            hours, minutes = divmod(plate["minutes"], 60)
            grams = sum(plate["grams"].values())
            lines.append(f"| {result['file']} | {plate['name']} | {hours} h {minutes:02} min | {grams:.1f} g |")
    (docs / "build-summary.md").write_text("\n".join(lines) + "\n")
    (docs / "build-summary.json").write_text(json.dumps(results, indent=1) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", choices=["a1-mini", "a2l"])
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--school", action="store_true", help="use the private SVG in reference/")
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    mark = design.SCHOOL_MARK if args.school else None
    if mark and not mark.is_file():
        parser.error("place the school artwork in reference/school-mark.svg")
    build = ROOT / "build" / ("school" if args.school else "")
    release = build / "release"
    docs = build / "docs" if args.school else ROOT / "docs"
    results = []
    for product, printer in [("counters", "a1-mini"), ("board", "a2l")]:
        if args.only and printer != args.only:
            continue
        project = make_project(product, build, mark, args.jobs)
        print(f"Slice-checking {project.key}", flush=True)
        result = bambu.build_project(project, build, release)
        results.append(result)
        if len(result["plates"]) != len(project.plates):
            raise RuntimeError(f"Missing plate in {project.key}")
        if product == "board":
            image = docs / "images" / "board.png"
            image.parent.mkdir(parents=True, exist_ok=True)
            with zipfile.ZipFile(build / "work" / project.key / "sliced" / "final.3mf") as archive:
                image.write_bytes(archive.read("Metadata/plate_1.png"))
    if not args.only:
        if not bd.export_step(design.playing_set(mark), str(release / "do-guti.step")):
            raise RuntimeError("STEP export failed")
        previous_summary = docs / "build-summary.json"
        if not args.school and previous_summary.is_file():
            previous = {r["key"]: r for r in json.loads(previous_summary.read_text())}
            results = [bambu.steady(previous.get(r["key"]), r) for r in results]
        write_summary(results, docs)


if __name__ == "__main__":
    main()
